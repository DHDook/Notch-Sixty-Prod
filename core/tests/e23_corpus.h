/* E23 T2: frozen reference corpus for the graph-vs-kernel parity tests.
 *
 * The kernel is deleted in E23 K2, so each parity test keeps what the kernel taught us as numbers. A corpus case holds,
 * per channel, the output summary: 64 equal-block RMS values (dB, floored at -120), the peak, and the first 64 samples
 * after the reported latency; then the test's own extras (see each test). A frozen run must match within 0.01 dB block
 * RMS and 1e-5 absolute per sample (and per extra, as the test states).
 *
 * The corpus is written only by a build with -DN60_E23_WRITE_CORPUS (which also compiles the kernel reference and runs
 * the original kernel comparison, so a regenerated corpus is still kernel-checked), with N60_E23_CORPUS_OUT naming the
 * output file. After K2 there is no kernel to build against, so a regeneration is a deliberate DSP change that needs a
 * cited reason in its PR. Plain C, no platform headers: the tests run on Linux too. */
#ifndef N60_E23_CORPUS_H
#define N60_E23_CORPUS_H

#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

#define E23_BLOCKS 64
#define E23_SAMPLES 64
#define E23_CH_VALUES (E23_BLOCKS + 1 + E23_SAMPLES)

/* Summarises n samples into out[E23_CH_VALUES]: block RMS dB, peak, then x[latency ..]. */
static inline void e23_summarise(const float *x, int n, int latency, double *out) {
    const int per = n / E23_BLOCKS;
    double peak = 0.0;
    for (int b = 0; b < E23_BLOCKS; b++) {
        double ss = 0.0;
        for (int i = b * per; i < (b + 1) * per; i++) {
            ss += (double)x[i] * x[i];
            if (fabs((double)x[i]) > peak) peak = fabs((double)x[i]);
        }
        const double db = 10.0 * log10(ss / per + 1e-30);
        out[b] = db < -120.0 ? -120.0 : db;
    }
    out[E23_BLOCKS] = peak;
    for (int i = 0; i < E23_SAMPLES; i++) out[E23_BLOCKS + 1 + i] = (latency + i < n) ? x[latency + i] : 0.0;
}

/* Compares one channel summary with the frozen one; returns the number of failures (printed). */
static inline int e23_compare(const double *got, const double *want, const char *label) {
    int fails = 0;
    for (int b = 0; b < E23_BLOCKS; b++) {
        if (!(fabs(got[b] - want[b]) <= 0.01)) {
            fprintf(stderr, "FAIL %s block %d RMS %.4f dB vs frozen %.4f dB\n", label, b, got[b], want[b]);
            if (++fails > 3) return fails;
        }
    }
    if (!(fabs(got[E23_BLOCKS] - want[E23_BLOCKS]) <= 1e-5)) {
        fprintf(stderr, "FAIL %s peak %.7g vs frozen %.7g\n", label, got[E23_BLOCKS], want[E23_BLOCKS]);
        fails++;
    }
    for (int i = 0; i < E23_SAMPLES; i++) {
        if (!(fabs(got[E23_BLOCKS + 1 + i] - want[E23_BLOCKS + 1 + i]) <= 1e-5)) {
            fprintf(stderr, "FAIL %s sample %d %.7g vs frozen %.7g\n", label, i, got[E23_BLOCKS + 1 + i], want[E23_BLOCKS + 1 + i]);
            if (++fails > 6) return fails;
        }
    }
    return fails;
}

#ifdef N60_E23_WRITE_CORPUS
static FILE *e23_out = NULL;
static inline void e23_open(const char *symbol) {
    const char *path = getenv("N60_E23_CORPUS_OUT");
    e23_out = path ? fopen(path, "w") : NULL;
    if (!e23_out) { fprintf(stderr, "set N60_E23_CORPUS_OUT to the corpus file to write\n"); exit(2); }
    fprintf(e23_out, "/* Generated by a N60_E23_WRITE_CORPUS run (see e23_corpus.h). Do not edit. */\nstatic const double %s[] = {\n", symbol);
}
static inline void e23_put(const double *v, int n) {
    for (int i = 0; i < n; i++) fprintf(e23_out, "%.7g,", v[i]);
    fputc('\n', e23_out);
}
static inline void e23_close(void) { fputs("};\n", e23_out); fclose(e23_out); }
#endif

#endif
